#!/usr/bin/env tsx
// Single source for UVPDockController ABI: regenerated from the Forge artifact
// under contracts/uvp-dock/out; never hand-copied and kept separate from the
// frozen contracts/uvp-contracts artifact-abis.ts.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageDir = resolve(scriptDir, "..");
const artifactPath = resolve(
  packageDir,
  "../../contracts/uvp-dock/out/UVPDockController.sol/UVPDockController.json",
);

interface FoundryArtifact {
  readonly abi: readonly unknown[];
}

async function main(): Promise<void> {
  const artifact = JSON.parse(
    await readFile(artifactPath, "utf8"),
  ) as FoundryArtifact;
  const output = `// Generated by scripts/generate-dock-controller-abi.ts from the Forge artifact
// of contracts/uvp-dock; do not edit by hand — rerun the generator instead.
export const DOCK_CONTROLLER_CONTRACT_NAME = "UVPDockController" as const;
export const DOCK_CONTROLLER_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
  await writeFile(resolve(packageDir, "src/dock-controller-abi.ts"), output);
  console.log(
    `wrote src/dock-controller-abi.ts (${artifact.abi.length} ABI entries)`,
  );
}

main().catch((error: unknown) => {
  console.error(
    error instanceof Error ? `${error.name}: ${error.message}` : String(error),
  );
  process.exitCode = 1;
});
